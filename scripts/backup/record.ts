/**
 * Backup-time record and restore comparison (docs/OPERATIONS.md "Backup and restore",
 * steps 0 and 4; DECISIONS A66).
 *
 *   BACKUP_DATABASE_URL: pnpm exec tsx scripts/backup/record.ts record --out record.json [--dump <file> [--pg-dump <path>]]
 *   RESTORE_DATABASE_URL: pnpm exec tsx scripts/backup/record.ts compare --record record.json --out drill.json
 *                                                  [--web-base-url http://host:port]
 *
 * `record` opens one REPEATABLE READ READ ONLY transaction on a single pooled connection,
 * exports its snapshot and, when `--dump` is given, runs `pg_dump --snapshot` on it, so the
 * record and the dump describe the same instant. Everything else the record holds (row counts
 * and checksums per public table, view checksums with and without the regenerated columns, the
 * latest `ingest_run` row per source, `sources.status` and a sample of public capability
 * answers through the same `dispatch` the API and MCP adapters use) is read inside that
 * transaction.
 *
 * `compare` takes the same record on the restore target and applies the comparison policy:
 * only `readModelRefreshedAt` / `refreshedAt` (and `person_card.refreshed_at`) are excluded;
 * when the record date and the drill date differ, the date-dependent fields (`isCurrent`,
 * `tenureYears`, `person_card.tenure_years`) are excluded too and each exclusion is listed.
 * Materialized views that came back unpopulated are refreshed (the only permitted refresh)
 * before comparing. Exit code 1 on any mismatch. Nothing here is a test fixture: it reads the
 * database it is pointed at.
 */
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { readFile, stat, writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import {
  type CapabilityContext,
  type CapabilityName,
  createDb,
  type DbHandle,
  dispatchByName,
} from '@civic-ledger/core';
import { sql } from 'drizzle-orm';
import { pgEnvironment, runTool, safeError } from './safety';

export const RECORD_VERSION = 2;

/** Regenerated by every read-model refresh; always excluded (OPERATIONS comparison policy). */
export const VOLATILE_KEYS = new Set(['readModelRefreshedAt', 'refreshedAt']);
/** Evaluated at the database's `current_date`; excluded only when record and drill dates differ. */
export const DATE_DEPENDENT_KEYS = new Set(['isCurrent', 'tenureYears']);

export interface TableRecord {
  count: number;
  checksum: string | null;
}

export interface ViewRecord {
  count: number;
  raw: string | null;
  /** `person_card`: over `to_jsonb(t) - 'refreshed_at'`. `person_card_scorecard`: same as raw. */
  normalized: string | null;
  /** `person_card`: also minus `tenure_years` (for a drill on another date). */
  normalizedNoTenure: string | null;
}

export interface IngestRunRecord {
  id: number;
  sourceId: string;
  scope: string;
  status: string;
  snapshotChecksum: string | null;
  counts: unknown;
  finishedAt: string | null;
}

export interface CapabilitySample {
  name: string;
  input: Record<string, unknown>;
  output: unknown;
}

export interface BackupRecord {
  version: number;
  takenAt: string;
  recordDate: string;
  serverVersion: string;
  snapshotId: string | null;
  tables: Record<string, TableRecord>;
  views: Record<string, ViewRecord>;
  ingestRuns: IngestRunRecord[];
  capabilities: CapabilitySample[];
  dump?: { file: string; bytes: number; sha256: string; pgDumpVersion: string; durationMs: number };
  timingsMs: Record<string, number>;
}

export interface Mismatch {
  item: string;
  recorded: unknown;
  current: unknown;
}

export interface CompareResult {
  recordDate: string;
  drillDate: string;
  sameDate: boolean;
  exclusions: string[];
  refreshedViews: string[];
  mismatches: Mismatch[];
  web?: {
    baseUrl: string;
    health: { status: number; body: unknown };
    healthStrict: { status: number; body: unknown };
    sourcesStatusMatches: boolean;
  };
  passed: boolean;
  timingsMs: Record<string, number>;
}

type Row = Record<string, unknown>;

async function rows<T = Row>(handle: DbHandle, query: ReturnType<typeof sql>): Promise<T[]> {
  return ((await handle.db.execute(query)) as unknown as { rows: T[] }).rows;
}

/** Remove the given keys at any depth; arrays keep their order. */
export function stripKeys(value: unknown, keys: ReadonlySet<string>): unknown {
  if (Array.isArray(value)) return value.map((v) => stripKeys(v, keys));
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Row)
        .filter(([key]) => !keys.has(key))
        .map(([key, v]) => [key, stripKeys(v, keys)]),
    );
  }
  return value;
}

/** Stable JSON: sorted object keys so equal values serialize identically. */
export function canonical(value: unknown): string {
  return JSON.stringify(value, (_key, v: unknown) => {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      return Object.fromEntries(Object.entries(v as Row).sort(([a], [b]) => (a < b ? -1 : 1)));
    }
    return v;
  });
}

/** Postgres returns `date` as a JS Date (local midnight) or string depending on the driver. */
function dateText(value: unknown): string {
  if (value instanceof Date) {
    const y = value.getFullYear();
    const m = String(value.getMonth() + 1).padStart(2, '0');
    const d = String(value.getDate()).padStart(2, '0');
    return `${y}-${m}-${d}`;
  }
  return String(value).slice(0, 10);
}

function openHandle(url: string): DbHandle {
  // One connection pins the exported snapshot; large checksums have a finite one-hour
  // statement/idle budget and operators still enforce their whole-job deadline.
  return createDb({
    kind: 'pg',
    url,
    poolMax: 1,
    statementTimeoutMs: 3_600_000,
    lockTimeoutMs: 30_000,
    idleInTransactionTimeoutMs: 3_600_000,
    idleTimeoutMs: 24 * 3_600_000,
    connectTimeoutMs: 30_000,
  });
}

async function tableRecords(handle: DbHandle): Promise<Record<string, TableRecord>> {
  const names = await rows<{ tablename: string }>(
    handle,
    sql`select tablename from pg_tables where schemaname = 'public' order by tablename`,
  );
  const out: Record<string, TableRecord> = {};
  for (const { tablename } of names) {
    out[tablename] = await checksumRows(handle, tablename);
  }
  return out;
}

/** Bounded client memory; the server can spill its deterministic sort to disk. */
async function checksumRows(
  handle: DbHandle,
  name: string,
  omit: string[] = [],
): Promise<TableRecord> {
  let expression = sql`to_jsonb(t)`;
  for (const key of omit) expression = sql`${expression} - ${key}`;
  await handle.db.execute(sql`declare backup_rows no scroll cursor for
    select (${expression})::text as value from ${sql.identifier(name)} t
    order by (${expression})::text collate "C"`);
  const hash = createHash('sha256');
  let count = 0;
  try {
    for (;;) {
      const batch = await rows<{ value: string }>(handle, sql`fetch 1000 from backup_rows`);
      if (batch.length === 0) break;
      for (const row of batch) hash.update(`${Buffer.byteLength(row.value)}:${row.value}\n`);
      count += batch.length;
    }
  } finally {
    await handle.db.execute(sql`close backup_rows`);
  }
  return { count, checksum: hash.digest('hex') };
}

async function viewRecords(handle: DbHandle): Promise<Record<string, ViewRecord>> {
  const names = await rows<{ matviewname: string }>(
    handle,
    sql`select matviewname from pg_matviews where schemaname = 'public' order by matviewname`,
  );
  const out: Record<string, ViewRecord> = {};
  for (const { matviewname } of names) {
    const raw = await checksumRows(handle, matviewname);
    const normalized = await checksumRows(handle, matviewname, ['refreshed_at']);
    const noTenure = await checksumRows(handle, matviewname, ['refreshed_at', 'tenure_years']);
    out[matviewname] = {
      count: raw.count,
      raw: raw.checksum,
      normalized: normalized.checksum,
      normalizedNoTenure: noTenure.checksum,
    };
  }
  return out;
}

async function ingestRunRecords(handle: DbHandle): Promise<IngestRunRecord[]> {
  const result = await rows<{
    id: number;
    source_id: string;
    scope: string;
    status: string;
    snapshot_checksum: string | null;
    counts: unknown;
    finished_at: Date | string | null;
  }>(
    handle,
    sql`select distinct on (source_id) id, source_id, scope, status, snapshot_checksum, counts, finished_at
        from ingest_run order by source_id, started_at desc, id desc`,
  );
  return result.map((r) => ({
    id: Number(r.id),
    sourceId: r.source_id,
    scope: r.scope,
    status: r.status,
    snapshotChecksum: r.snapshot_checksum,
    counts: r.counts,
    finishedAt:
      r.finished_at instanceof Date ? r.finished_at.toISOString() : (r.finished_at ?? null),
  }));
}

/** JSON round trip: Dates become ISO strings, as the API serializes them. */
function plain(value: unknown): unknown {
  return JSON.parse(JSON.stringify(value));
}

/**
 * The fixed sample: `sources.status`, then for the first two people (scope `all`) `people.get`,
 * `money.summary`, `votes.list`, `scores.list`; `explore.table` over scope `all`;
 * `frameworks.evaluate` with the first stored framework over those people. Inputs are stored in
 * the record so the drill replays exactly them.
 */
async function capabilitySamples(ctx: CapabilityContext): Promise<CapabilitySample[]> {
  const samples: CapabilitySample[] = [];
  const run = async (name: CapabilityName, input: Record<string, unknown>) => {
    const output = plain(await dispatchByName(name, input, ctx));
    samples.push({ name, input, output });
    return output;
  };
  await run('sources.status', {});
  const people = (await run('people.search', { scope: 'all', limit: 2 })) as {
    items: Array<{ slug: string }>;
  };
  const slugs = people.items.map((p) => p.slug);
  for (const slug of slugs) {
    await run('people.get', { slug });
    await run('money.summary', { slug });
    await run('votes.list', { slug, limit: 20 });
    await run('scores.list', { slug });
  }
  await run('explore.table', { filters: { scope: 'all' }, limit: 50 });
  const frameworks = (await run('frameworks.list', {})) as {
    items: Array<{ spec: Record<string, unknown> }>;
  };
  const spec = frameworks.items[0]?.spec;
  if (spec && slugs.length > 0) {
    await run('frameworks.evaluate', { framework: spec, people: { slugs }, limit: 10 });
  }
  return samples;
}

async function sha256File(path: string): Promise<string> {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(path)) hash.update(chunk as Buffer);
  return hash.digest('hex');
}

export interface RecordOptions {
  url: string;
  dumpFile?: string;
  pgDump?: string;
  log?: (line: string) => void;
}

export async function takeRecord({
  url,
  dumpFile,
  pgDump = 'pg_dump',
  log = () => {},
}: RecordOptions): Promise<BackupRecord> {
  const timings: Record<string, number> = {};
  const timed = async <T>(label: string, work: () => Promise<T>): Promise<T> => {
    const started = performance.now();
    const value = await work();
    timings[label] = Math.round(performance.now() - started);
    log(`${label}: ${timings[label]} ms`);
    return value;
  };
  const handle = openHandle(url);
  try {
    await handle.db.execute(sql`set time zone 'UTC'`);
    await handle.db.execute(sql`begin isolation level repeatable read read only`);
    const [meta] = await rows<{ today: unknown; version: string; snapshot: string }>(
      handle,
      sql`select current_date as today, current_setting('server_version') as version,
                 pg_export_snapshot() as snapshot`,
    );
    if (!meta) throw new Error('could not read database metadata');
    const record: BackupRecord = {
      version: RECORD_VERSION,
      takenAt: new Date().toISOString(),
      recordDate: dateText(meta.today),
      serverVersion: meta.version,
      snapshotId: meta.snapshot,
      tables: {},
      views: {},
      ingestRuns: [],
      capabilities: [],
      timingsMs: timings,
    };
    // The dump runs first so the snapshot transaction is not idle while it works.
    if (dumpFile) {
      await timed('pg_dump', async () => {
        const started = performance.now();
        const stdout = await runTool(pgDump, ['--version']);
        const dumpMajor = Number(/PostgreSQL\) (\d+)/.exec(stdout)?.[1]);
        if (dumpMajor !== Number(meta.version.split('.')[0])) {
          throw new Error('pg_dump major version must match the source server');
        }
        await runTool(
          pgDump,
          ['--format=custom', '--no-owner', `--snapshot=${meta.snapshot}`, `--file=${dumpFile}`],
          pgEnvironment(url),
        );
        const info = await stat(dumpFile);
        record.dump = {
          file: 'civic-ledger.dump',
          bytes: info.size,
          sha256: await sha256File(dumpFile),
          pgDumpVersion: stdout.trim(),
          durationMs: Math.round(performance.now() - started),
        };
      });
    }
    record.tables = await timed('tables', () => tableRecords(handle));
    record.views = await timed('views', () => viewRecords(handle));
    record.ingestRuns = await timed('ingest_runs', () => ingestRunRecords(handle));
    record.capabilities = await timed('capabilities', () => capabilitySamples({ db: handle.db }));
    await handle.db.execute(sql`commit`);
    return record;
  } finally {
    await handle.close();
  }
}

export interface CompareOptions {
  url: string;
  record: BackupRecord;
  refreshIfEmpty?: boolean;
  webBaseUrl?: string;
  fetchImpl?: typeof fetch;
  log?: (line: string) => void;
}

/**
 * Pure comparison of a recorded state against the current state of the restore target, under
 * the documented policy. Exported so the policy itself is unit-testable without a database.
 */
export function compareRecords(
  recorded: BackupRecord,
  current: BackupRecord,
  refreshedViews: string[] = [],
): Omit<CompareResult, 'timingsMs' | 'web'> {
  const sameDate = recorded.recordDate === current.recordDate;
  const exclusions: string[] = [
    'capability keys readModelRefreshedAt, refreshedAt (regenerated at refresh)',
    'person_card.refreshed_at (view checksum taken over to_jsonb(t) - refreshed_at)',
  ];
  const keys = new Set(VOLATILE_KEYS);
  if (!sameDate) {
    for (const k of DATE_DEPENDENT_KEYS) keys.add(k);
    exclusions.push(
      `record date ${recorded.recordDate} != drill date ${current.recordDate}: capability keys isCurrent, tenureYears and person_card.tenure_years excluded`,
    );
  }
  const mismatches: Mismatch[] = [];
  const check = (item: string, a: unknown, b: unknown) => {
    if (canonical(a) !== canonical(b)) mismatches.push({ item, recorded: a, current: b });
  };

  for (const name of new Set([...Object.keys(recorded.tables), ...Object.keys(current.tables)])) {
    check(`table ${name}`, recorded.tables[name] ?? null, current.tables[name] ?? null);
  }
  for (const name of new Set([...Object.keys(recorded.views), ...Object.keys(current.views)])) {
    const a = recorded.views[name];
    const b = current.views[name];
    if (!a || !b) {
      check(`view ${name}`, a ?? null, b ?? null);
      continue;
    }
    check(`view ${name} count`, a.count, b.count);
    if (name === 'person_card') {
      check(
        sameDate ? `view ${name} normalized checksum` : `view ${name} checksum minus tenure_years`,
        sameDate ? a.normalized : a.normalizedNoTenure,
        sameDate ? b.normalized : b.normalizedNoTenure,
      );
    } else {
      check(`view ${name} raw checksum`, a.raw, b.raw);
    }
  }
  check('ingest_run latest rows', recorded.ingestRuns, current.ingestRuns);

  const currentByKey = new Map(current.capabilities.map((c) => [canonical([c.name, c.input]), c]));
  for (const sample of recorded.capabilities) {
    const match = currentByKey.get(canonical([sample.name, sample.input]));
    if (!match) {
      mismatches.push({ item: `capability ${sample.name}`, recorded: sample.input, current: null });
      continue;
    }
    check(
      `capability ${sample.name} ${JSON.stringify(sample.input).slice(0, 80)}`,
      stripKeys(sample.output, keys),
      stripKeys(match.output, keys),
    );
  }
  return {
    recordDate: recorded.recordDate,
    drillDate: current.recordDate,
    sameDate,
    exclusions,
    refreshedViews,
    mismatches,
    passed: mismatches.length === 0,
  };
}

export async function compareAgainst({
  url,
  record,
  refreshIfEmpty = true,
  webBaseUrl,
  fetchImpl = fetch,
  log = () => {},
}: CompareOptions): Promise<CompareResult> {
  const timings: Record<string, number> = {};
  const started = performance.now();
  const refreshed: string[] = [];
  if (refreshIfEmpty) {
    const handle = openHandle(url);
    try {
      const views = await rows<{ matviewname: string; ispopulated: boolean }>(
        handle,
        sql`select matviewname, ispopulated from pg_matviews where schemaname='public'`,
      );
      const empty: string[] = [];
      for (const view of views) {
        if (!view.ispopulated) {
          empty.push(view.matviewname);
          continue;
        }
        const [count] = await rows<{ count: number }>(
          handle,
          sql`select count(*)::int as count from ${sql.identifier(view.matviewname)}`,
        );
        if (count?.count === 0 && (record.views[view.matviewname]?.count ?? 0) > 0)
          empty.push(view.matviewname);
      }
      if (empty.length > 0) {
        log(`refreshing unpopulated views: ${empty.join(', ')}`);
        for (const name of ['person_card', 'person_card_scorecard']) {
          const populated = views.find((view) => view.matviewname === name)?.ispopulated;
          if (populated)
            await handle.db.execute(
              sql`refresh materialized view concurrently ${sql.identifier(name)}`,
            );
          else await handle.db.execute(sql`refresh materialized view ${sql.identifier(name)}`);
        }
        refreshed.push(...empty);
      }
    } finally {
      await handle.close();
    }
    timings.refresh_check = Math.round(performance.now() - started);
  }
  const replay = await takeRecordWithInputs(url, record, log);
  timings.record_on_target = replay.timingsMs.total ?? 0;
  const result: CompareResult = {
    ...compareRecords(record, replay.record, refreshed),
    timingsMs: timings,
  };

  if (webBaseUrl) {
    const endpoint = new URL(webBaseUrl);
    if (
      !['http:', 'https:'].includes(endpoint.protocol) ||
      endpoint.username ||
      endpoint.password ||
      endpoint.search ||
      endpoint.hash ||
      endpoint.pathname !== '/'
    )
      throw new Error('web smoke URL must be an HTTP(S) origin without credentials');
    const baseUrl = endpoint.origin;
    const webStarted = performance.now();
    const get = async (path: string) => {
      const response = await fetchImpl(`${baseUrl}${path}`, {
        headers: { accept: 'application/json' },
        signal: AbortSignal.timeout(10_000),
      });
      const text = await response.text();
      let body: unknown = text;
      try {
        body = JSON.parse(text);
      } catch {
        // keep text
      }
      return { status: response.status, body };
    };
    const health = await get('/api/health');
    const healthStrict = await get('/api/health?strict=1');
    const sources = await get('/api/v1/sources.status');
    const recordedSources = record.capabilities.find((c) => c.name === 'sources.status');
    const keys = new Set(VOLATILE_KEYS);
    const sourcesStatusMatches =
      sources.status === 200 &&
      canonical(stripKeys(sources.body, keys)) ===
        canonical(stripKeys(recordedSources?.output, keys));
    if (health.status !== 200) {
      result.mismatches.push({
        item: 'web /api/health status',
        recorded: 200,
        current: health.status,
      });
    }
    if (!sourcesStatusMatches) {
      result.mismatches.push({
        item: 'web /api/v1/sources.status (normalized)',
        recorded: stripKeys(recordedSources?.output, keys),
        current: stripKeys(sources.body, keys),
      });
    }
    result.web = { baseUrl, health, healthStrict, sourcesStatusMatches };
    result.passed = result.mismatches.length === 0;
    timings.web = Math.round(performance.now() - webStarted);
  }
  timings.total = Math.round(performance.now() - started);
  return result;
}

/** Re-take the record on the target, replaying exactly the recorded capability inputs. */
async function takeRecordWithInputs(
  url: string,
  recorded: BackupRecord,
  log: (line: string) => void,
): Promise<{ record: BackupRecord; timingsMs: Record<string, number> }> {
  const started = performance.now();
  const handle = openHandle(url);
  try {
    await handle.db.execute(sql`set time zone 'UTC'`);
    await handle.db.execute(sql`begin isolation level repeatable read read only`);
    const [meta] = await rows<{ today: unknown; version: string }>(
      handle,
      sql`select current_date as today, current_setting('server_version') as version`,
    );
    if (!meta) throw new Error('could not read database metadata');
    const ctx: CapabilityContext = { db: handle.db };
    const capabilities: CapabilitySample[] = [];
    for (const sample of recorded.capabilities) {
      capabilities.push({
        name: sample.name,
        input: sample.input,
        output: plain(await dispatchByName(sample.name, sample.input, ctx)),
      });
    }
    const record: BackupRecord = {
      version: RECORD_VERSION,
      takenAt: new Date().toISOString(),
      recordDate: dateText(meta.today),
      serverVersion: meta.version,
      snapshotId: null,
      tables: await tableRecords(handle),
      views: await viewRecords(handle),
      ingestRuns: await ingestRunRecords(handle),
      capabilities,
      timingsMs: {},
    };
    await handle.db.execute(sql`commit`);
    const total = Math.round(performance.now() - started);
    log(`record on target: ${total} ms`);
    return { record, timingsMs: { total } };
  } finally {
    await handle.close();
  }
}

export function formatReport(result: CompareResult): string {
  const lines = [
    `Restore comparison: ${result.passed ? 'PASS' : 'FAIL'}`,
    `record date ${result.recordDate}, drill date ${result.drillDate} (${result.sameDate ? 'same date: date-dependent fields compared exactly' : 'different dates'})`,
    `refreshed views: ${result.refreshedViews.length ? result.refreshedViews.join(', ') : 'none (restore left them populated)'}`,
    'exclusions:',
    ...result.exclusions.map((e) => `  - ${e}`),
  ];
  if (result.web) {
    lines.push(
      `web ${result.web.baseUrl}: /api/health ${result.web.health.status}, /api/health?strict=1 ${result.web.healthStrict.status} (freshness: separate result, not integrity), sources.status normalized ${result.web.sourcesStatusMatches ? 'equal' : 'DIFFERENT'}`,
    );
  }
  lines.push(`mismatches: ${result.mismatches.length}`);
  for (const m of result.mismatches) {
    lines.push(
      `  - ${m.item}: recorded ${JSON.stringify(m.recorded)?.slice(0, 200)} / current ${JSON.stringify(m.current)?.slice(0, 200)}`,
    );
  }
  lines.push(`timings ms: ${JSON.stringify(result.timingsMs)}`);
  return lines.join('\n');
}

async function main(argv: string[]): Promise<number> {
  const [mode, ...rest] = argv;
  const { values } = parseArgs({
    args: rest,
    options: {
      out: { type: 'string' },
      dump: { type: 'string' },
      'pg-dump': { type: 'string' },
      record: { type: 'string' },
      'web-base-url': { type: 'string' },
    },
  });
  const url =
    mode === 'compare' ? process.env.RESTORE_DATABASE_URL : process.env.BACKUP_DATABASE_URL;
  if (!url)
    throw new Error('BACKUP_DATABASE_URL (record) or RESTORE_DATABASE_URL (compare) is required');
  const log = (line: string) => process.stderr.write(`[record] ${line}\n`);
  if (mode === 'record') {
    if (!values.out) throw new Error('--out <record.json> is required');
    const started = performance.now();
    const record = await takeRecord({
      url,
      dumpFile: values.dump,
      pgDump: values['pg-dump'] ?? process.env.PG_DUMP ?? 'pg_dump',
      log,
    });
    record.timingsMs.total = Math.round(performance.now() - started);
    await writeFile(values.out, `${JSON.stringify(record, null, 2)}\n`);
    log(
      `record written: ${values.out} (${Object.keys(record.tables).length} tables, ${record.capabilities.length} capability answers, date ${record.recordDate}, total ${record.timingsMs.total} ms)`,
    );
    return 0;
  }
  if (mode === 'compare') {
    if (!values.record) throw new Error('--record <record.json> is required');
    const record = JSON.parse(await readFile(values.record, 'utf8')) as BackupRecord;
    if (record.version !== RECORD_VERSION) {
      throw new Error(`record version ${record.version} is not ${RECORD_VERSION}`);
    }
    const result = await compareAgainst({
      url,
      record,
      refreshIfEmpty: false,
      webBaseUrl: values['web-base-url'],
      log,
    });
    if (values.out) await writeFile(values.out, `${JSON.stringify(result, null, 2)}\n`);
    process.stdout.write(`${formatReport(result)}\n`);
    return result.passed ? 0 : 1;
  }
  process.stderr.write(
    'usage: record.ts record --out record.json [--dump <file> [--pg-dump <path>]] (BACKUP_DATABASE_URL)\n' +
      '       record.ts compare --record record.json [--out drill.json] [--web-base-url <url>] (RESTORE_DATABASE_URL; read-only comparison)\n',
  );
  return 2;
}

if (process.argv[1] && /record\.ts$/.test(process.argv[1].replace(/\\/g, '/'))) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (error) => {
      process.stderr.write(`[record] ${safeError(error)}\n`);
      process.exit(1);
    },
  );
}
